import type { Issue, IssueSeverity } from './issues.ts';
import type { Manifest } from './manifest.ts';

export interface PageReport {
	source: string;
	output: string;
	status: string;
	issues: Issue[];
}

export interface MigrationReport {
	generatedBy: string;
	upstream: Manifest['upstream'];
	summary: Manifest['summary'];
	pages: PageReport[];
	conflicts: { file: string; reason: string }[];
	skipped: Manifest['skipped'];
	ignoredFiles: Manifest['ignoredFiles'];
	assetsNotMirrored: Manifest['assetsNotMirrored'];
}

const SEVERITY_ORDER: IssueSeverity[] = ['error', 'warning', 'info'];

function escapeCell(value: string): string {
	return value.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function code(value: string): string {
	const clean = value.replace(/\n/g, ' ');
	return clean.includes('`') ? `\`\` ${clean} \`\`` : `\`${clean}\``;
}

export function renderMigrationReport(report: MigrationReport): string {
	const { upstream, summary } = report;
	const lines: string[] = [];
	lines.push('# Migration report', '');
	lines.push('> Generated by `pnpm docs:import`. Do not edit by hand.', '');
	lines.push(`- **Upstream:** [${upstream.name}](${upstream.repository}) at commit [\`${upstream.commit.slice(0, 7)}\`](${upstream.repository}/commit/${upstream.commit}) (${upstream.commitDate})`);
	lines.push(`- **Upstream license:** ${upstream.license} — preserved in \`third-party/elysia-documentation/LICENSE\``);
	if (upstream.versionEvidence) {
		lines.push(
			`- **Version evidence:** upstream \`${upstream.versionEvidence.source}\` declares \`${upstream.versionEvidence.package}@${upstream.versionEvidence.range}\``
		);
	}
	lines.push('');

	lines.push('## Summary', '', '| Metric | Count |', '| --- | ---: |');
	lines.push(`| Discovered Markdown pages | ${summary.discovered} |`);
	lines.push(`| Imported pages | ${summary.imported} |`);
	lines.push(`| … of which with warnings | ${summary.importedWithWarnings} |`);
	lines.push(`| Failed pages | ${summary.failed} |`);
	lines.push(`| Skipped pages | ${summary.skipped} |`);
	lines.push(`| Errors | ${summary.issues.error} |`);
	lines.push(`| Warnings | ${summary.issues.warning} |`);
	lines.push(`| Informational notes | ${summary.issues.info} |`);
	lines.push(`| Assets mirrored | ${summary.assetsMirrored} |`);
	lines.push(`| Assets not mirrored (policy) | ${summary.assetsNotMirrored} |`);
	lines.push(`| Missing assets (referenced but absent upstream) | ${summary.assetsMissing} |`);
	lines.push(`| Local-edit conflicts | ${report.conflicts.length} |`);
	lines.push('');

	if (report.conflicts.length > 0) {
		lines.push('## Conflicts', '', 'These generated files were not overwritten:', '');
		for (const conflict of report.conflicts) lines.push(`- \`${conflict.file}\`: ${conflict.reason}`);
		lines.push('');
	}

	const allIssues = report.pages.flatMap((page) => page.issues);
	const byCode = new Map<string, { severity: IssueSeverity; count: number }>();
	for (const issue of allIssues) {
		const key = `${issue.severity}:${issue.code}`;
		const entry = byCode.get(key) ?? { severity: issue.severity, count: 0 };
		entry.count++;
		byCode.set(key, entry);
	}
	lines.push('## Issues by category', '', '| Severity | Category | Count |', '| --- | --- | ---: |');
	const sorted = [...byCode.entries()].sort(
		([a, x], [b, y]) => SEVERITY_ORDER.indexOf(x.severity) - SEVERITY_ORDER.indexOf(y.severity) || a.localeCompare(b)
	);
	for (const [key, entry] of sorted) lines.push(`| ${entry.severity} | \`${key.split(':')[1]}\` | ${entry.count} |`);
	lines.push('');

	const unresolved = report.pages.filter((page) => page.issues.some((issue) => issue.severity !== 'info'));
	lines.push('## Unresolved conversion issues', '');
	if (unresolved.length === 0) lines.push('None.', '');
	for (const page of unresolved) {
		lines.push(`### \`${page.source}\``, '');
		lines.push(`Output: \`${page.output}\` — status: ${page.status}`, '');
		for (const issue of page.issues.filter((entry) => entry.severity !== 'info')) {
			const location = issue.line ? ` (line ${issue.line})` : '';
			const source = issue.source ? ` — ${code(issue.source.slice(0, 160))}` : '';
			lines.push(`- **${issue.severity}** \`${issue.code}\`${location}: ${issue.message}${source}`);
		}
		lines.push('');
	}

	const brokenLinks = allIssues.filter((issue) => issue.code === 'broken-link' || issue.code === 'broken-anchor');
	lines.push('## Broken links found in upstream content', '');
	if (brokenLinks.length === 0) lines.push('None.', '');
	else {
		lines.push('| Page | Line | Link | Problem |', '| --- | ---: | --- | --- |');
		for (const issue of brokenLinks) {
			lines.push(`| \`${issue.file ?? ''}\` | ${issue.line ?? ''} | ${code(issue.source ?? '')} | ${escapeCell(issue.message)} |`);
		}
		lines.push('');
	}

	const missing = report.assetsNotMirrored.filter((asset) => asset.status === 'missing');
	lines.push('## Missing assets', '');
	if (missing.length === 0) lines.push('None.', '');
	else {
		lines.push('| Asset | Referenced by |', '| --- | --- |');
		for (const asset of missing) lines.push(`| \`${asset.source}\` | ${asset.referencedBy.map((p) => `\`${p}\``).join(', ')} |`);
		lines.push('');
	}

	const excluded = report.assetsNotMirrored.filter((asset) => asset.status === 'excluded');
	lines.push('## Assets not mirrored (asset policy)', '');
	lines.push('Referenced from imported pages but not copied; they are linked on the official site instead. See ATTRIBUTION.md.', '');
	if (excluded.length === 0) lines.push('None.', '');
	else {
		lines.push('| Asset | Reason | Referenced by |', '| --- | --- | --- |');
		for (const asset of excluded) {
			lines.push(`| \`${asset.source}\` | ${escapeCell(asset.reason)} | ${asset.referencedBy.map((p) => `\`${p}\``).join(', ')} |`);
		}
		lines.push('');
	}

	lines.push('## Skipped pages', '', '| Page | Reason |', '| --- | --- |');
	for (const page of report.skipped) lines.push(`| \`${page.source}\` | ${escapeCell(page.reason)} |`);
	lines.push('');

	lines.push('## Non-page files in content directories', '', '| File | Reason |', '| --- | --- |');
	for (const file of report.ignoredFiles) lines.push(`| \`${file.source}\` | ${escapeCell(file.reason)} |`);
	lines.push('');

	lines.push(
		'## Informational transformations',
		'',
		'Expected, intentional transformations (for example removed `<script setup>` blocks and Twoslash markers) are listed per page with their original source in `reports/migration-report.json`.',
		''
	);
	return `${lines.join('\n').trimEnd()}\n`;
}
